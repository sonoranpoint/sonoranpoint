const { JSDOM } = require("jsdom");
const fs = require("fs");
const src = fs.readFileSync(process.argv[2], "utf8");
const errors = [];
const dom = new JSDOM("<!doctype html><html><body>" + src + "</body></html>", { runScripts: "dangerously", pretendToBeVisual: true, url: "https://example.test/",
  beforeParse(w) { w.matchMedia = () => ({ matches: false, addEventListener() {} }); w.scrollTo = () => {}; } });
dom.window.addEventListener("error", (e) => errors.push(e.message + " @" + e.lineno));
const E = (s) => dom.window.eval(s), doc = dom.window.document;
const check = (c, m, t) => { console.log((c ? "pass  " : "FAIL  ") + m + (c ? "" : "\n      " + (t || ""))); if (!c) process.exitCode = 1; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const go = async (r) => { dom.window.location.hash = r; await sleep(30); };
const click = async (sel) => { const el = doc.querySelector(sel); if (!el) throw new Error("missing " + sel); el.click(); await sleep(15); };
const submit = async (sel, vals) => { const f = doc.querySelector(sel); for (const [k, v] of Object.entries(vals)) f.elements[k].value = v; f.dispatchEvent(new dom.window.Event("submit", { bubbles: true, cancelable: true })); await sleep(20); };
const drawer = () => doc.querySelector(".drawer")?.textContent.replace(/\s+/g, " ") || "";
const page = () => doc.querySelector(".main").textContent.replace(/\s+/g, " ");
const setChecks = (name, vals) => doc.querySelectorAll(`.drawer input[name="${name}"]`).forEach((cb) => { cb.checked = vals.includes(cb.value); });
const change = async (el, v) => { if (typeof v === "boolean") el.checked = v; else el.value = v; el.dispatchEvent(new dom.window.Event("change", { bubbles: true })); await sleep(15); };
(async () => {
  await sleep(100);
  await go("settings");
  const rows = () => [...doc.querySelectorAll(".ctree .crow:not(.top) input.cname")].map((i) => i.value);
  check(JSON.stringify(rows()) === JSON.stringify(["BW", "Delta BW", "United BW", "AW", "Delta AW", "United AW"]), "settings shows the contract tree, groups first then what's under them");
  check(/Whole company/.test(page()) && doc.querySelectorAll('input[data-contract="aw"][data-k="share"]:checked').length === 1 && doc.querySelectorAll('input[data-contract="bw"][data-k="share"]:checked').length === 0,
        "each group has its own sharing switch (AW on, BW off)");
  await click('[data-act="addContract"][data-id="aw"]');
  await submit('[data-form="newContract:aw"]', { name: "American AW" });
  check(rows().includes("American AW") && E("contractOf(DB.contracts.find(c => c.name === 'American AW').parent).name") === "AW", "add a contract under a group");
  await click('[data-act="addContract"][data-id="aw"]'); await submit('[data-form="newContract:aw"]', { name: "delta aw" });
  check(/already one with that name/.test(doc.body.textContent), "no two with the same name in a group");
  await click('[data-act="askDelContract"][data-id="dbw"]'); await click('[data-act="doDelContract"]');
  check(E("!!contractOf('dbw')") && /Move its/.test(doc.body.textContent), "a contract with people or gear in it can't be deleted");
  const am = E("DB.contracts.find(c => c.name === 'American AW').id");
  await click(`[data-act="askDelContract"][data-id="${am}"]`); await click('[data-act="doDelContract"]');
  check(!rows().includes("American AW"), "an empty one can");
  const sw = doc.querySelector('input[data-contract="bw"][data-k="share"]'); sw.checked = true; sw.dispatchEvent(new dom.window.Event("change", { bubbles: true })); await sleep(15);
  check(E("contractOf('bw').share") === true, "turn sharing on for a group");
  const top = doc.querySelector('input[data-contract=""][data-k="move"]'); top.checked = true; top.dispatchEvent(new dom.window.Event("change", { bubbles: true })); await sleep(15);
  check(E("DB.org.settings.move_on_return") === true, "and the company-level switches");
  await submit('[data-form="contractWord"]', { word: "Accounts" });
  check(E("CTERM().one") === "Account" && /Accounts/.test(page()), "rename what they're called (Accounts)");
  await submit('[data-form="contractWord"]', { word: "Contract" });

  await go("equipment");
  const sel = doc.querySelector("#eqContract"); sel.value = "bw"; sel.dispatchEvent(new dom.window.Event("input", { bubbles: true })); await sleep(20);
  check([...doc.querySelectorAll("tbody tr")].length > 0 && E("S.eqRows.every(x => ['dbw','ubw'].includes(x.contract))"), "filter equipment by a group (includes everything under it)");
  check(/Delta BW/.test(doc.querySelector("tbody").textContent), "each item shows its contract");
  E("S.f.eqContract = ''; render()");
  const vac = E("DB.equipment.find(q => q.name === 'Vacuum 01').id");
  E(`openDrawer('eqForm', '${vac}')`); await sleep(20);
  await submit('[data-form^="eq:"]', { contract: "uaw" });
  check(E(`eqOf('${vac}').contract`) === "uaw", "move an item to another contract from its form");
  await go("employees");
  E(`openDrawer('empForm', '${E("DB.employees[0].id")}')`); await sleep(20);
  await submit('[data-form^="emp:"]', { contract: "" });
  check(E("DB.employees[0].contract") === null, "a person can be in no contract (works everywhere)");
  await go("stations");
  E("openDrawer('station', 'st2')"); await sleep(20);
  await submit('[data-form="stationEdit:st2"]', { contract: "daw" });
  check(E("DB.stations.find(s => s.id === 'st2').contract") === "daw" && /Delta AW/.test(page()), "set a station's contract from its panel");
  // Loans (BW back to not sharing)
  E("contractOf('bw').share = false");
  await go("equipment");
  check(/On loan · Delta BW/.test(page()), "an item on loan shows who has it");
  await click('[data-seg="eqStatus:loan"]');
  check(doc.querySelectorAll("tbody tr").length === 1, "filter to items on loan");
  E("S.f.eqStatus = 'all'; render()");
  const b6 = E("DB.equipment.find(q => q.name === 'Battery 06').id");
  E(`openDrawer('equipment', '${b6}')`); await sleep(20);
  check(/On loan to Delta BW/.test(drawer()) && /Delta.s chargers are down/.test(drawer()) && /Belongs toUnited BW/.test(drawer()), "its panel says whose it is and who has it", drawer().slice(0, 600));
  await click(".drawer [data-act=endLoan]");
  check(!E(`loanOf('${b6}')`) && /Earlier loans \(1\)/.test(drawer()), "end the loan; it stays in the item's history");
  const opts = [...doc.querySelectorAll('.drawer [data-form^="lend:"] option')].map((o) => o.textContent.trim());
  check(opts.includes("Delta BW") && !opts.includes("United BW") && !opts.includes("BW"), "lend to: only contracts that can't already use it");
  const f = doc.querySelector('.drawer [data-form^="lend:"]'); f.elements.to.value = "daw";
  await submit('.drawer [data-form^="lend:"]', { notes: "Swap for a radio" });
  check(E(`loanOf('${b6}').to`) === "daw" && /Lent to Delta AW/.test(doc.body.textContent), "lend it again from the panel");
  // Part 2: the Show switcher
  E("DB.contracts.find(c => c.id === 'uaw') || DB.contracts.push({ id: 'uaw', parent: 'aw', name: 'United AW', sort: 9 }); render()");
  await go("equipment");
  const vs = doc.querySelector("#viewSel");
  check(vs && [...vs.options].map((o) => o.textContent.trim()).includes("Delta BW"), "the top bar has a Show switcher with the contracts");
  vs.value = "dbw"; vs.dispatchEvent(new dom.window.Event("change", { bubbles: true })); await sleep(20);
  check(E("api.equipment().every(q => !q.contract || ['dbw','bw'].includes(q.contract))") && E("api.equipment().length") > 0, "Show Delta BW: only Delta BW (and company-wide) equipment");
  check(E("api.employees().every(e => !e.contract || ['dbw','bw'].includes(e.contract))"), "...people");
  check(E("api.stations().every(x => !x.contract || ['dbw','bw'].includes(x.contract))") && E("api.stations().length") === 1, "...stations");
  check(E("api.shiftReports().every(r => !r.shift.contract || r.shift.contract === 'dbw')"), "...and shift reports");
  await go("shifts");
  const names = () => [...doc.querySelectorAll(".main table tbody td:first-child b")].map((b) => b.textContent);
  check(!names().includes("PM") && names().includes("AM"), "...and shifts (United's PM shift is hidden)");
  const vs2 = doc.querySelector("#viewSel"); vs2.value = ""; vs2.dispatchEvent(new dom.window.Event("change", { bubbles: true })); await sleep(20);
  check(names().includes("PM"), "All contracts brings everything back");

  // Who sees what (Team access)
  await go("team");
  check(/Sees/.test(page()) && /Delta BW/.test(doc.querySelector(".main table").textContent), "Team access shows what each person covers (Kelly: Delta BW)");
  E("openDrawer('memberScope', 'u4')"); await sleep(20);
  check(/What Ops sees/.test(drawer()) && doc.querySelectorAll('.drawer input[name=c]').length >= 6, "pick contracts for someone");
  doc.querySelector('.drawer input[name=c][value="ubw"]').checked = true;
  doc.querySelector('.drawer form').dispatchEvent(new dom.window.Event("submit", { bubbles: true, cancelable: true })); await sleep(20);
  check(JSON.stringify(E("DB.members.find(m => m.id === 'u4').contracts")) === '["ubw"]', "saved: Ops Office now covers United BW");
  check(!E("api.setMemberContracts('u1', ['dbw']).ok"), "owners always see everything");
  // Shift belongs to a contract
  E(`openDrawer('shiftForm', DB.shifts.find(x => x.name === 'Overnight').id)`); await sleep(20);
  await submit('[data-form^="shift:"]', { contract: "daw" });
  check(E("DB.shifts.find(x => x.name === 'Overnight').contract") === "daw", "a shift belongs to a contract");
  check(errors.length === 0, "no script errors " + errors.join(";"));
  process.exit();
})();
