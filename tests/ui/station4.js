const E = (s) => dom.window.eval(s);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const doc = dom.window.document;
const text = () => doc.querySelector("#screen").textContent.replace(/\s+/g, " ").trim();
const check = (c, m) => { console.log((c ? "pass  " : "FAIL  ") + m + (c ? "" : "\n      screen: " + text().slice(0, 400))); if (!c) process.exitCode = 1; };
const click = async (sel, ms = 60) => { const el = doc.querySelector("#screen " + sel); if (!el) throw new Error("no element " + sel + " :: " + text().slice(0, 250)); el.click(); await sleep(ms); };
const fk = async (str) => { for (const ch of str) await click(`[data-fk="${ch}"]`, 5); };
const tap = async (uid, ms = 500) => { E(`handleTag('${uid}')`); await sleep(ms); };
